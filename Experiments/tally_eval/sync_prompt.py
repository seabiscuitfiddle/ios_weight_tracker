"""Extracts the shipped prompt and schema out of `Sources/TallyCore/LLM/ParsePrompt.swift`.

The baseline every variant is measured against has to be the prompt the app actually sends,
byte for byte. A hand-copied Markdown file is that only on the day it is written, so the
baseline is generated from the Swift source instead and regenerated whenever the source moves.

Run it as a module from `Experiments/`:

    python -m tally_eval.sync_prompt

which rewrites `prompts/shipped.md` and `prompts/shipped.schema.json`, or with `--check` to
fail when they are stale — the form worth wiring into CI.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

EXPERIMENTS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = EXPERIMENTS_DIR.parent
PARSE_PROMPT_SWIFT = REPO_ROOT / "Sources" / "TallyCore" / "LLM" / "ParsePrompt.swift"

SYSTEM_OUT = EXPERIMENTS_DIR / "prompts" / "shipped.md"
SCHEMA_OUT = EXPERIMENTS_DIR / "prompts" / "shipped.schema.json"

GENERATED_HEADER = (
    "<!-- Generated by `python -m tally_eval.sync_prompt` from "
    "Sources/TallyCore/LLM/ParsePrompt.swift. Do not edit by hand: edit the Swift source, or "
    "copy this file to a new name to make a variant. -->\n\n"
)


class SwiftSourceError(RuntimeError):
    """The Swift source no longer has the shape this extractor assumes."""


# MARK: Swift literal reading


def _string_constants(source: str) -> dict[str, str]:
    """Single-line `static let name = "value"` constants, for resolving interpolations.

    Only the simple form is read, because only the simple form is interpolated into the two
    literals this module cares about. Anything more elaborate should fail loudly at
    interpolation time rather than be guessed at here.
    """
    pattern = re.compile(r'static let (\w+)\s*=\s*"((?:[^"\\]|\\.)*)"')
    return {name: _unescape_single_line(value) for name, value in pattern.findall(source)}


def _unescape_single_line(value: str) -> str:
    return value.replace('\\"', '"').replace("\\\\", "\\").replace("\\n", "\n")


def _multiline_literal(source: str, name: str) -> str:
    """The raw body of `static let <name> = \"\"\"…\"\"\"`, before escapes are resolved.

    Swift dedents a multiline literal by the indentation of its *closing* delimiter, so that is
    what is stripped here rather than the shallowest line — they differ whenever a literal
    contains an indented block, which the JSON schema very much does.
    """
    opener = re.search(rf'static let {re.escape(name)}\s*=\s*"""[ \t]*\n', source)
    if opener is None:
        raise SwiftSourceError(f"No multiline literal named `{name}` in {PARSE_PROMPT_SWIFT.name}.")

    body_start = opener.end()
    closer = re.compile(r'^([ \t]*)"""', re.MULTILINE).search(source, body_start)
    if closer is None:
        raise SwiftSourceError(f"Literal `{name}` is never closed.")

    indent = closer.group(1)
    lines = source[body_start : closer.start()].split("\n")
    if lines and lines[-1] == "":
        lines.pop()

    dedented = []
    for line in lines:
        if line.strip() and not line.startswith(indent):
            raise SwiftSourceError(
                f"Line in `{name}` is indented less than its closing delimiter: {line!r}"
            )
        dedented.append(line[len(indent) :] if line.startswith(indent) else line.lstrip())
    return "\n".join(dedented)


def _resolve_escapes(literal: str, constants: dict[str, str]) -> str:
    """Applies the escapes Swift applies: continuations, interpolations, and backslash pairs.

    A backslash at end of line joins the two lines with no separator at all — that is how the
    prompt's paragraphs are written in the source and why a naive read of the file produces text
    with hard wraps the model never sees.
    """
    out: list[str] = []
    index = 0
    length = len(literal)

    while index < length:
        char = literal[index]
        if char != "\\":
            out.append(char)
            index += 1
            continue

        if index + 1 >= length:
            raise SwiftSourceError("Literal ends with a dangling backslash.")

        following = literal[index + 1]
        if following == "\n":  # Line continuation: the newline is not part of the string.
            index += 2
        elif following == "(":
            end = literal.index(")", index)
            expression = literal[index + 2 : end].strip()
            if expression not in constants:
                raise SwiftSourceError(
                    f"Cannot resolve interpolation `\\({expression})`; only simple string "
                    "constants declared in the same file are supported."
                )
            out.append(constants[expression])
            index = end + 1
        elif following in '\\"':
            out.append(following)
            index += 2
        elif following == "n":
            out.append("\n")
            index += 2
        elif following == "t":
            out.append("\t")
            index += 2
        else:
            raise SwiftSourceError(f"Unsupported escape `\\{following}` in literal.")

    return "".join(out)


# MARK: Extraction


def extract(swift_path: Path = PARSE_PROMPT_SWIFT) -> tuple[str, dict]:
    """Returns the system prompt as text and the output schema as a parsed object."""
    source = swift_path.read_text(encoding="utf-8")
    constants = _string_constants(source)

    system = _resolve_escapes(_multiline_literal(source, "system"), constants)
    schema_text = _resolve_escapes(_multiline_literal(source, "outputSchema"), constants)

    try:
        schema = json.loads(schema_text)
    except json.JSONDecodeError as error:  # Worth naming: it means the shipped schema is broken.
        raise SwiftSourceError(f"`outputSchema` is not valid JSON once resolved: {error}") from error

    return system, schema


def rendered() -> tuple[str, str]:
    """The exact bytes the two generated files should hold."""
    system, schema = extract()
    return GENERATED_HEADER + system + "\n", json.dumps(schema, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the generated files are stale, without rewriting them.",
    )
    args = parser.parse_args(argv)

    system_text, schema_text = rendered()
    targets = [(SYSTEM_OUT, system_text), (SCHEMA_OUT, schema_text)]

    if args.check:
        stale = [
            path
            for path, expected in targets
            if not path.exists() or path.read_text(encoding="utf-8") != expected
        ]
        for path in stale:
            print(f"stale: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        if stale:
            print("Run `python -m tally_eval.sync_prompt` to regenerate.", file=sys.stderr)
            return 1
        print("Prompt files are in sync with ParsePrompt.swift.")
        return 0

    for path, content in targets:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
